/**
 * Klyro — ASM (Algorithmic State Machine) Chart Generator
 *
 * Automatically converts an FSM graph into a clean, vertically-aligned Algorithmic State Machine (ASM) chart:
 * - State Boxes (Rectangles): Display state name, binary encoding [Q], and Moore outputs
 * - Decision Diamonds: Test input conditions (e.g., "X=1", "m=0") along the vertical spine
 * - Conditional Output Boxes (Ovals): Display Mealy outputs activated when input conditions hold
 * - Orthogonal Wire Rails: Dedicated non-overlapping tracks:
 *     - Vertical central spine for sequential next-state transitions
 *     - Staggered left rails for loop-backs to prior states
 *     - Inner right rail for forward leap transitions
 *     - Outer right rail for wrap-around from final state back to origin
 */

import type {
  ASMBlock,
  ASMChartData,
  ASMEdge,
  FSMState,
  FSMTransition,
  MachineType,
  StateEncodingMap,
} from './types'

// ── Layout Geometry Constants ────────────────────────────────────────────────
const SPINE_X = 380
const STATE_BOX_WIDTH = 180
const DECISION_DIAMOND_WIDTH = 130
const START_Y = 60
const STATE_SPACING_Y = 240
const DECISION_Y_OFFSET = 95
const CONDITIONAL_OUTPUT_Y_OFFSET = 65

// ── Rail Routing Offsets ─────────────────────────────────────────────────────
const SPINE_OFFSET = 20
const WRAP_AROUND_OUTER_OFFSET = 90
const FORWARD_SKIP_INNER_OFFSET = 40
const BASE_LOOPBACK_LEFT_OFFSET = 35
const LOOPBACK_STAGGER_STEP = 25

/**
 * Transforms an FSM definition into structured ASM chart nodes and orthogonal edges.
 *
 * @param states List of FSM states
 * @param transitions Transitions connecting states
 * @param inputNames Input signals driving decision branches
 * @param outputNames Output signals generated by the machine
 * @param machineType 'moore' (outputs in state box) or 'mealy' (outputs in conditional boxes)
 * @param encodings Map of state IDs to binary code strings
 * @returns ASM blocks (nodes) and orthogonal connecting edges
 */
export function generateASMChart(
  states: FSMState[],
  transitions: FSMTransition[],
  inputNames: string[],
  outputNames: string[],
  machineType: MachineType,
  encodings: StateEncodingMap
): ASMChartData {
  const blocks: ASMBlock[] = []
  const edges: ASMEdge[] = []

  if (states.length === 0) return { blocks, edges }

  states.forEach((state, stateIdx) => {
    const stateY = START_Y + stateIdx * STATE_SPACING_Y
    const stateBlockId = `asm-state-${state.id}`

    // 1. State Box (centered on vertical spine)
    blocks.push({
      id: stateBlockId,
      type: 'state',
      stateId: state.id,
      name: state.name,
      code: encodings[state.id] ?? '',
      outputs: machineType === 'moore' ? state.mooreOutputs : undefined,
      x: SPINE_X - STATE_BOX_WIDTH / 2,
      y: stateY,
    })

    const outgoing = transitions.filter((t) => t.fromState === state.id)
    if (outgoing.length === 0) return

    // Check if transitions are conditioned on an input variable
    const hasCondition = outgoing.some(
      (t) => t.condition && t.condition !== '1' && t.condition.toLowerCase() !== 'always'
    )

    if (hasCondition) {
      // Determine condition variable name (e.g. "m" or "X")
      let condVar = inputNames[0] ?? 'X'
      for (const t of outgoing) {
        if (t.condition.includes('=')) {
          const varPart = t.condition.split('=')[0]?.trim()
          if (varPart) {
            condVar = varPart
            break
          }
        }
      }

      const decY = stateY + DECISION_Y_OFFSET
      const decisionBlockId = `asm-dec-${state.id}`

      // 2. Decision Diamond (centered on spine beneath State Box)
      blocks.push({
        id: decisionBlockId,
        type: 'decision',
        stateId: state.id,
        name: condVar,
        conditionVar: condVar,
        x: SPINE_X - DECISION_DIAMOND_WIDTH / 2,
        y: decY,
      })

      // Downward flow from State Box into Decision Diamond
      edges.push({
        id: `edge-${stateBlockId}-${decisionBlockId}`,
        source: stateBlockId,
        target: decisionBlockId,
        sourceHandle: 'bottom',
        targetHandle: 'top',
        offset: 15,
      })

      // Identify True (1) and False (0) transitions
      const trueTrans = outgoing.find(
        (t) =>
          t.condition.includes('=1') ||
          t.condition.includes('= 1') ||
          t.condition === condVar ||
          t.condition === '1'
      )
      const falseTrans = outgoing.find(
        (t) =>
          t.condition.includes('=0') ||
          t.condition.includes('= 0') ||
          t.condition.startsWith('!') ||
          t.condition.startsWith('~')
      )

      const branchesToProcess: Array<{ trans: FSMTransition; label: string; isTrue: boolean }> = []
      if (trueTrans) {
        branchesToProcess.push({ trans: trueTrans, label: '1', isTrue: true })
      }
      if (falseTrans && falseTrans.id !== trueTrans?.id) {
        branchesToProcess.push({ trans: falseTrans, label: '0', isTrue: false })
      }

      // If neither matched by regex pattern, fall back to sequential order
      if (branchesToProcess.length === 0) {
        if (outgoing[0]) branchesToProcess.push({ trans: outgoing[0], label: '1', isTrue: true })
        if (outgoing[1]) branchesToProcess.push({ trans: outgoing[1], label: '0', isTrue: false })
      }

      branchesToProcess.forEach(({ trans, label, isTrue }) => {
        const targetIdx = states.findIndex((s) => s.id === trans.toState)
        const targetStateId = `asm-state-${trans.toState}`

        const hasMealy =
          machineType === 'mealy' &&
          outputNames.some((o) => (trans.mealyOutputs[o] ?? 0) === 1)

        // Determine orthogonal routing handles and track offsets to prevent wire overlap
        let sourceHandle: 'bottom' | 'left' | 'right' = 'bottom'
        let targetHandle: 'top' | 'left' | 'right' = 'top'
        let offset = SPINE_OFFSET

        const isSequentialNext = targetIdx === stateIdx + 1
        const isWrapAroundToStart = targetIdx === 0 && stateIdx === states.length - 1
        const isLoopBack = targetIdx <= stateIdx && !isWrapAroundToStart
        const isForwardSkip = targetIdx > stateIdx + 1

        if (isSequentialNext) {
          // Straight down central spine
          sourceHandle = 'bottom'
          targetHandle = 'top'
          offset = SPINE_OFFSET
        } else if (isWrapAroundToStart) {
          // Outer right rail: wide track so it never collides with inner rail
          sourceHandle = 'right'
          targetHandle = 'top'
          offset = WRAP_AROUND_OUTER_OFFSET
        } else if (isLoopBack) {
          // Left rail looping back up to an earlier state
          // Stagger offsets across states so each return loop has its own dedicated track
          sourceHandle = 'left'
          targetHandle = 'left'
          offset = BASE_LOOPBACK_LEFT_OFFSET + ((stateIdx % 4) * LOOPBACK_STAGGER_STEP)
        } else if (isForwardSkip) {
          // Inner right rail: forward jump track runs inside the wrap-around rail
          sourceHandle = 'right'
          targetHandle = 'right'
          offset = FORWARD_SKIP_INNER_OFFSET
        } else {
          sourceHandle = isTrue ? 'bottom' : 'left'
          targetHandle = 'top'
          offset = 25
        }

        if (hasMealy) {
          // Conditional Output Box (Oval / Rounded rectangle) for Mealy machines
          const condOutId = `asm-cond-${trans.id}`
          let condX = SPINE_X - 60
          let condY = decY + CONDITIONAL_OUTPUT_Y_OFFSET

          if (sourceHandle === 'left') {
            condX = SPINE_X - 160
            condY = decY
          } else if (sourceHandle === 'right') {
            condX = SPINE_X + 160
            condY = decY
          }

          blocks.push({
            id: condOutId,
            type: 'conditional_output',
            stateId: state.id,
            name: 'Outputs',
            outputs: trans.mealyOutputs,
            x: condX,
            y: condY,
          })

          edges.push({
            id: `edge-${decisionBlockId}-${condOutId}`,
            source: decisionBlockId,
            target: condOutId,
            sourceHandle,
            targetHandle: 'top',
            label,
            offset: 15,
          })

          edges.push({
            id: `edge-${condOutId}-${targetStateId}`,
            source: condOutId,
            target: targetStateId,
            sourceHandle: 'bottom',
            targetHandle,
            offset,
          })
        } else {
          edges.push({
            id: `edge-${decisionBlockId}-${targetStateId}-${label}`,
            source: decisionBlockId,
            target: targetStateId,
            sourceHandle,
            targetHandle,
            label,
            offset,
          })
        }
      })
    } else {
      // Unconditional transition (straight state-to-state flow)
      const t = outgoing[0]
      if (t) {
        const targetIdx = states.findIndex((s) => s.id === t.toState)
        const targetId = `asm-state-${t.toState}`

        let sourceHandle: 'bottom' | 'left' | 'right' = 'bottom'
        let targetHandle: 'top' | 'left' | 'right' = 'top'
        let offset = SPINE_OFFSET

        if (targetIdx === stateIdx + 1) {
          sourceHandle = 'bottom'
          targetHandle = 'top'
          offset = SPINE_OFFSET
        } else if (targetIdx === 0 && stateIdx === states.length - 1) {
          sourceHandle = 'right'
          targetHandle = 'top'
          offset = WRAP_AROUND_OUTER_OFFSET
        } else if (targetIdx <= stateIdx) {
          sourceHandle = 'left'
          targetHandle = 'left'
          offset = BASE_LOOPBACK_LEFT_OFFSET + ((stateIdx % 4) * LOOPBACK_STAGGER_STEP)
        } else {
          sourceHandle = 'right'
          targetHandle = 'right'
          offset = FORWARD_SKIP_INNER_OFFSET
        }

        edges.push({
          id: `edge-${stateBlockId}-${targetId}`,
          source: stateBlockId,
          target: targetId,
          sourceHandle,
          targetHandle,
          offset,
        })
      }
    }
  })

  return { blocks, edges }
}

